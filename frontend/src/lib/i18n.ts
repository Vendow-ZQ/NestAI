export type CopyKey = keyof typeof copy.zh

export function getCopy(language: AppLanguage, key: CopyKey): string {
  return copy[language][key] || copy.zh[key]
}

export function useI18n() {
  const language = useLanguageStore((s) => s.language)
  const t = useCallback((key: CopyKey) => getCopy(language, key), [language])
  const pick = useCallback((text: { zh: string; en: string }) => text[language], [language])

  return {
    language,
    isEnglish: language === 'en',
    t,
    pick,
  }
}
